const test = require('node:test'), assert = require('node:assert'), fs = require('fs'), path = require('path'), os = require('os');
const H = require('./helpers');
Object.assign(process.env, { SOURCE: 'csv', SAMPLE_DIR: H.tmpSample(), ADMIN_KEY: 'ck', DATA_DIR: fs.mkdtempSync(path.join(os.tmpdir(), 'mc-')), DEFAULT_SLOTS_VISIBLE: 'true' });
const { app, refresh } = require('../public/server');
let base, server; const errors = [];
test.before(async () => { await refresh(); ({ server, base } = await H.listen(app)); });
test.after(() => server.close());
const post = (p, b) => fetch(base + p, { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify(b) });
const FAR = Date.UTC(2090, 0, 1), PAST = Date.UTC(2021, 0, 1);

test('Motions tab: released dates show the text, others say when they release (IST)', async () => {
  await post('/host/ck/motions', { date: '2026-10-21', motions: { Junior: 'This House would ban homework', Senior: 'THW abolish the UN Security Council' } });
  await post('/host/ck/motions/release', { date: '2026-10-21', action: 'set', at: PAST });
  await post('/host/ck/motions', { date: '2026-10-22', motions: { Junior: 'HIDDEN-UNTIL-RELEASE' } });
  await post('/host/ck/motions/release', { date: '2026-10-22', action: 'set', at: Date.UTC(2026, 9, 18, 18, 30) + 2 * 86400000 * 4000 });
  await post('/host/ck/motions/release', { date: '2026-10-23', action: 'hold' });
  const dom = await H.page(base + '/', errors), d = dom.window.document;
  assert.deepStrictEqual([...d.querySelectorAll('#tabs button')].filter(b => !b.hidden).map(b => b.textContent).slice(-1), ['Motions']);
  assert.ok(await H.openTab(dom, 'find'), 'page loaded');
  d.querySelector('[data-tab=motions]').click();
  assert.ok(await H.until(() => d.querySelectorAll('#mOut .mcard').length === 11));
  const cards = [...d.querySelectorAll('#mOut .mcard')];
  assert.match(cards[0].textContent, /Wed 21 Oct/); assert.match(cards[0].textContent, /Released/);
  assert.match(cards[0].textContent, /ban homework/); assert.match(cards[0].textContent, /Security Council/);
  assert.ok(!/Middle/.test(cards[0].textContent), 'a category with no motion is not shown');
  assert.match(cards[1].textContent, /Releases \d+ \w+, \d+:\d\d (AM|PM) IST/); assert.ok(!/HIDDEN/.test(d.body.innerHTML));
  assert.match(cards[2].textContent, /Release time to be announced/);
  assert.match(cards[3].textContent, /Releases 2[0-9] Oct, 12:00 AM IST|Releases \d+ Oct, 12:00 AM IST/);
  dom.window.close();
});
test('Motions stay reachable when the schedule is switched off', async () => {
  await post('/host/ck/switch', { slots: false });
  const dom = await H.page(base + '/', errors), d = dom.window.document;
  assert.ok(await H.until(() => /released soon/.test(d.getElementById('loading').textContent)));
  assert.ok(!d.getElementById('v-home').hidden, 'opens on Home');
  assert.deepStrictEqual([...d.querySelectorAll('#homeLinks button')].map(b => b.getAttribute('data-go')), ['motions'], 'only Motions is offered');
  d.querySelector('#homeLinks button').click();
  assert.ok(await H.until(() => d.querySelectorAll('#mOut .mcard').length === 11));
  assert.ok(!d.getElementById('v-motions').hidden);
  dom.window.close();
  await post('/host/ck/switch', { slots: true });
});
test('host page: type motions, tick Visible, untick, optional time, backup link', async () => {
  const dom = await H.page(base + '/host/ck', errors), d = dom.window.document;
  assert.ok(await H.until(() => d.querySelectorAll('#mdays .mday').length === 11), 'one block per date');
  assert.match(d.querySelectorAll('#mdays .mday summary')[0].textContent, /Wed 21 Oct.*Released/, 'released by the earlier test');
  assert.match(d.querySelectorAll('#mdays .mday summary')[4].textContent, /Sun 25 Oct.*Scheduled for 22 Oct, 12:00 AM IST/);
  assert.match(d.getElementById('backup').getAttribute('href'), /\/host\/ck\/backup$/);
  const day = d.querySelectorAll('#mdays .mday')[4];                        // Sun 25 Oct
  day.querySelector('textarea').value = 'THW test the host page';
  [...day.querySelectorAll('button')].find(b => b.textContent === 'Save motions').click();
  assert.ok(await H.until(() => /Saved at/.test(day.querySelector('.mbody .row .mmini').textContent)));
  assert.match(day.querySelector('summary').textContent, /1 of 3 entered/);
  assert.strictEqual((await (await fetch(base + '/host/ck/motions')).json()).dates[4].m.Junior, 'THW test the host page');
  dom.window.confirm = () => true;
  const chk = day.querySelector('.mvis input'), tick = on => { chk.checked = on; chk.dispatchEvent(new dom.window.Event('change')); };
  assert.strictEqual(chk.checked, false);
  const day25 = async () => (await (await fetch(base + '/api/motions')).json()).dates[4];
  tick(true);
  assert.ok(await H.until(() => /Released/.test(day.querySelector('.mstate').textContent)));
  assert.strictEqual((await day25()).m.Junior, 'THW test the host page', 'ticking shows it to students');
  tick(false);
  assert.ok(await H.until(() => /On hold/.test(day.querySelector('.mstate').textContent)));
  assert.strictEqual((await day25()).ok, 0, 'unticking hides it again');
  const input = day.querySelector('input[type=datetime-local]'); input.value = '2026-10-22T09:30';
  [...day.querySelectorAll('button')].find(b => b.textContent === 'Set time').click();
  assert.ok(await H.until(() => /Release time saved/.test(day.querySelector('.mbody .row .mmini').textContent)));
  assert.match(day.querySelector('.mstate').textContent, /On hold/, 'a held date stays hidden after setting a time');
  assert.strictEqual((await (await fetch(base + '/host/ck/motions')).json()).dates[4].at, Date.UTC(2026, 9, 22, 4, 0));
  [...day.querySelectorAll('button')].find(b => b.textContent === 'Use default').click();
  assert.ok(await H.until(() => /Scheduled for 22 Oct, 12:00 AM IST/.test(day.querySelector('.mstate').textContent)));
  assert.strictEqual(chk.checked, false);
  const auto = d.getElementById('swMAuto'); assert.strictEqual(auto.checked, true);
  auto.checked = false; auto.dispatchEvent(new dom.window.Event('change'));
  assert.ok(await H.until(() => /Automatic release is off/.test(d.getElementById('mmsg').textContent)));
  assert.match(d.querySelectorAll('#mdays .mday summary')[5].textContent, /Not visible: tick "Visible to students"/);
  auto.checked = true; auto.dispatchEvent(new dom.window.Event('change'));
  assert.ok(await H.until(() => /Automatic release is on/.test(d.getElementById('mmsg').textContent)));
  dom.window.close();
});
test('no script errors', () => assert.deepStrictEqual(errors, []));
